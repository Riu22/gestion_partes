CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger AS $$
BEGIN
INSERT INTO public.perfiles (
    id, email, nombre, apellidos, rol, activo,
    especialidad, codigo, postventa, grupo_profesional
) VALUES (
             new.id,
             new.email,
             COALESCE(new.raw_user_meta_data->>'nombre', ''),
             COALESCE(new.raw_user_meta_data->>'apellidos', ''),
             COALESCE(new.raw_user_meta_data->>'rol', 'OPERARIO')::public.usuario_rol,
             true,
             COALESCE(new.raw_user_meta_data->>'especialidad', 'ELECTRICIDAD'),
             new.raw_user_meta_data->>'codigo',
             COALESCE((new.raw_user_meta_data->>'postventa')::boolean, false),
             new.raw_user_meta_data->>'grupo_profesional'
         );
RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION public.sync_user_role()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
Set search_path = public, pg_catalog
AS $$
BEGIN
UPDATE auth.users
SET raw_user_meta_data = jsonb_set(raw_user_meta_data, '{rol}', TO_JSONB(NEW.rol))
WHERE id = NEW.id;
RETURN NEW;
END;
$$;

