-- =============================================
-- TIPOS
-- =============================================

CREATE TYPE public.usuario_rol AS ENUM (
    'ADMINISTRACION',
    'GESTION',
    'OPERARIO',
    'JEFE_DE_OBRA',
    'ENCARGADO'
);

CREATE TYPE public.ausencia_tipo AS ENUM ('BAJA', 'VACACIONES', 'PATERNIDAD');

-- =============================================
-- TABLAS
-- =============================================

CREATE TABLE public.perfiles (
                                 id                uuid NOT NULL,
                                 email             text,
                                 nombre            text,
                                 apellidos         text,
                                 codigo            text,
                                 rol               public.usuario_rol DEFAULT 'OPERARIO'::public.usuario_rol,
                                 jefe_directo_id   uuid,
                                 activo            boolean DEFAULT true,
                                 postventa         boolean DEFAULT false,
                                 especialidad      text,
                                 grupo_profesional text,
                                 creado_el         timestamp with time zone DEFAULT now(),
                                 CONSTRAINT perfiles_pkey        PRIMARY KEY (id),
                                 CONSTRAINT perfiles_email_key   UNIQUE (email),
                                 CONSTRAINT perfiles_codigo_key  UNIQUE (codigo),
                                 CONSTRAINT perfiles_especialidad_check
                                     CHECK (especialidad = ANY (ARRAY['ELECTRICIDAD'::text, 'FONTANERIA'::text]))
);

CREATE TABLE public.obras (
                              id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              nombre     text NOT NULL,
                              ubicacion  text NOT NULL,
                              municipio  text NOT NULL,
                              poblacion  text NOT NULL,
                              codigo     text NOT NULL,
                              activa     boolean DEFAULT true,
                              creado_el  timestamp with time zone DEFAULT now(),
                              postventa   boolean DEFAULT false,
                              CONSTRAINT obras_codigo_key UNIQUE (codigo)
);

CREATE TABLE public.asignaciones_obra (
                                          id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          perfil_id         uuid,
                                          obra_id           bigint,
                                          fecha_asignacion  timestamp with time zone DEFAULT now(),
                                          CONSTRAINT unica_asignacion_perfil_obra UNIQUE (perfil_id, obra_id)
);

CREATE TABLE public.partes_trabajo (
                                       id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       usuario_id         uuid REFERENCES public.perfiles(id) ON DELETE CASCADE,
                                       point_obra_id      bigint REFERENCES public.obras(id) ON DELETE SET NULL,
                                       fecha              date NOT NULL,
                                       horas_normales     numeric(4,2) DEFAULT 8.0,
                                       horas_extra        numeric(4,2) DEFAULT 0.0,
                                       descripcion_tareas text,
                                       especialidad       text CHECK (especialidad IN ('ELECTRICIDAD', 'FONTANERIA')),
                                       creado_por_gestor  boolean NOT NULL DEFAULT FALSE,
                                       firma_url          text,
                                       nombre_firmador    text,
                                       trabajos_extra     text,
                                       creado_el          timestamp with time zone DEFAULT now()
);

CREATE TABLE public.partes_jefe (
                                    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    usuario_id            uuid,
                                    fecha                 date DEFAULT CURRENT_DATE,
                                    descripcion_tareas    text,
                                    fecha_inicio          date,
                                    fecha_fin             date,
                                    total_horas_laborables numeric(8,2),
                                    creado_el             timestamp with time zone DEFAULT now()
);

CREATE TABLE public.partes_jefe_obras (
                                          id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          parte_jefe_id        bigint,
                                          obra_id              bigint,
                                          horas_electricas     numeric(8,2) NOT NULL DEFAULT 0,
                                          horas_mecanicas      numeric(8,2) NOT NULL DEFAULT 0,
                                          porcentaje_electrico numeric(5,2) NOT NULL DEFAULT 0,
                                          porcentaje_mecanico  numeric(5,2) NOT NULL DEFAULT 0
);

CREATE TABLE public.fechas_permitidas (
                                          id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          perfil_id  uuid NOT NULL,
                                          fecha      date NOT NULL,
                                          creado_el  timestamp with time zone DEFAULT now(),
                                          CONSTRAINT unica_fecha_perfil UNIQUE (perfil_id, fecha),
                                          CONSTRAINT fechas_permitidas_perfil_id_fkey
                                              FOREIGN KEY (perfil_id) REFERENCES public.perfiles(id) ON DELETE CASCADE
);

CREATE TABLE public.ausencias (
                                  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  perfil_id    uuid NOT NULL,
                                  tipo         public.ausencia_tipo NOT NULL,
                                  fecha_inicio date NOT NULL,
                                  fecha_fin    date NOT NULL,
                                  observaciones text,
    -- obra_id solo se usa cuando tipo = 'VACACIONES'.
    -- NULL → imputa a oficina (LUM); valor → imputa a esa obra en la quincena.
                                  obra_id      bigint,
                                  creado_el    timestamp with time zone DEFAULT now(),
                                  CONSTRAINT ausencias_perfil_id_fkey
                                      FOREIGN KEY (perfil_id) REFERENCES public.perfiles(id) ON DELETE CASCADE,
                                  CONSTRAINT ausencias_obra_id_fkey
                                      FOREIGN KEY (obra_id) REFERENCES public.obras(id) ON DELETE SET NULL
);

