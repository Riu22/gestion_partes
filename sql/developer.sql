-- Borramos triggers y funciones primero
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
DROP FUNCTION IF EXISTS public.handle_new_user();

-- Borramos las tablas (CASCADE elimina también las claves foráneas)
DROP TABLE IF EXISTS public.partes_trabajo CASCADE;
DROP TABLE IF EXISTS public.perfiles CASCADE;
DROP TABLE IF EXISTS public.obras CASCADE;

-- Borramos el tipo de rol
DROP TYPE IF EXISTS public.usuario_rol CASCADE;

-- ==========================================
-- 2. CREACIÓN DE ESTRUCTURA (DESDE CERO)
-- ==========================================

-- Crear el tipo ENUM para los roles
CREATE TYPE public.usuario_rol AS ENUM (
    'ADMINISTRACION',
    'GESTION',
    'OPERARIO',
    'JEFE_DE_OBRA',
    'ENCARGADO_DE_OBRA'
    );

-- Crear tabla de Obras
CREATE TABLE public.obras (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              nombre TEXT NOT NULL,
                              ubicacion TEXT NOT NULL,
                              municipio TEXT NOT NULL,
                              poblacion TEXT NOT NULL,
                              fecha_inicio DATE DEFAULT CURRENT_DATE,
                              activa BOOLEAN DEFAULT TRUE,
                              creado_el TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Crear tabla de Perfiles
CREATE TABLE public.perfiles (
                                 id UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
                                 email TEXT UNIQUE,
                                 nombre_completo TEXT,
                                 rol usuario_rol DEFAULT 'OPERARIO',
                                 activo BOOLEAN DEFAULT TRUE,
                                 creado_el TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Crear tabla de Partes de Trabajo
CREATE TABLE public.partes_trabajo (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       usuario_id UUID REFERENCES public.perfiles(id) ON DELETE CASCADE,
                                       obra_id BIGINT REFERENCES public.obras(id) ON DELETE SET NULL,
                                       fecha DATE DEFAULT CURRENT_DATE,
                                       horas_normales DECIMAL(4,2) DEFAULT 8.0,
                                       horas_extra DECIMAL(4,2) DEFAULT 0.0,
                                       descripcion_tareas TEXT,
                                       firmado BOOLEAN DEFAULT FALSE,
                                       creado_el TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- ==========================================
-- 3. AUTOMATIZACIÓN (TRIGGERS)
-- ==========================================

-- Función para crear perfil automáticamente
CREATE OR REPLACE FUNCTION public.handle_new_user()
    RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.perfiles (id, email, nombre_completo, rol)
    VALUES (
               new.id,
               new.email,
               COALESCE(new.raw_user_meta_data->>'full_name', 'Nuevo Usuario'),
               'OPERARIO'
           );
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Crear el trigger en auth.users
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

