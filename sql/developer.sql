CREATE INDEX idx_asignacion_obra_obra ON public.asignaciones_obra(obra_id);
CREATE INDEX idx_asignacion_encargado ON public.asignaciones_encargado(encargado_id);
CREATE INDEX idx_asignacion_operario ON public.asignaciones_encargado(operario_id);
CREATE INDEX idx_partes_usuario_id ON public.partes_trabajo(usuario_id);
CREATE INDEX idx_partes_obra_id ON public.partes_trabajo(point_obra_id);

-- ==========================================
-- 5. TRIGGER: crear perfil al registrar usuario
-- ==========================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
    RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    INSERT INTO public.perfiles (id, email, nombre_completo, rol)
    VALUES (
               new.id,
               new.email,
               COALESCE(new.raw_user_meta_data->>'full_name', 'Nuevo Usuario'),
               COALESCE(
                       (new.raw_user_meta_data->>'rol')::public.usuario_rol,
                       'OPERARIO'
               )
           );
    RETURN NEW;
END;
$$;

CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

