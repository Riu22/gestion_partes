package com.example.gestion_partes.model;

/*
 * ENUM: especialidad (oficios o especialidades de los trabajadores)
 *
 * Este enumerado define las especialidades tecnicas que puede tener
 * un trabajador en la empresa. Sirve para clasificar los partes de
 * trabajo segun el tipo de tarea realizada.
 *
 * Valores posibles:
 * - ELECTRICIDAD:  trabajos relacionados con instalaciones electricas
 * - FONTANERIA:    trabajos relacionados con instalaciones de agua/gas
 */
public enum especialidad {
    ELECTRICIDAD,
    FONTANERIA
}